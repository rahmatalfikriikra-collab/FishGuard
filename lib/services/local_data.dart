/// Reads the data bundled in `assets/data/`, which mirrors the shape the
/// Python worker (`pdpi_worker.py`) publishes from the FishGuard backend:
/// GeoJSON for DPI points, JSON for the BMKG maritime forecast.
///
/// Nothing here touches the network. Per PRD 5.0 ("darat-dulu"), everything
/// that needs the internet is downloaded on land and read from this local
/// layer at sea.
class LocalDataSource {
  LocalDataSource();

  List<DpiPoint>? _dpiCache;
  List<WeatherArea>? _weatherCache;

  /// Bundled asset text, tolerant of a UTF-8 BOM written by Windows tooling.
  Future<String> _readAsset(String path) async {
    final String raw = await rootBundle.loadString(path);
    return raw.startsWith('﻿') ? raw.substring(1) : raw;
  }

  /// Every WPP file the build shipped, discovered rather than listed.
  ///
  /// The pack is regenerated by `tool/real/build_real_data.dart` from the
  /// tables KKP actually published, so the set of zones changes as KKP
  /// publishes. Reading the asset manifest means a new zone appears in the app
  /// without anyone remembering to edit a hard-coded list here.
  static const String _dpiDir = 'assets/data';

  Future<List<String>> _bundledWpps() async {
    try {
      final AssetManifest manifest = await AssetManifest.loadFromAssetBundle(
        rootBundle,
      );
      final List<String> out = <String>[];
      for (final String key in manifest.listAssets()) {
        final RegExpMatch? m =
            RegExp(r'assets/data/dpi_(\d+)\.json$').firstMatch(key);
        if (m != null) out.add(m.group(1)!);
      }
      out.sort();
      if (out.isNotEmpty) return out;
    } catch (_) {
      // Fall through to the known set below.
    }
    return <String>['713', '714'];
  }

  Future<List<DpiPoint>> loadDpi({bool forceReload = false}) async {
    if (_dpiCache != null && !forceReload) return _dpiCache!;
    final List<DpiPoint> all = <DpiPoint>[];
    for (final String wpp in await _bundledWpps()) {
      try {
        final String raw = await _readAsset('$_dpiDir/dpi_$wpp.json');
        final Map<String, dynamic> j = jsonDecode(raw) as Map<String, dynamic>;
        final List<dynamic> feats = j['features'] as List<dynamic>? ?? <dynamic>[];
        for (final dynamic e in feats) {
          final DpiPoint p = DpiPoint.fromGeoJson(e as Map<String, dynamic>);
          if (!p.onLand && (LandMask.loaded == null || !LandMask.loaded!.isLand(p.lat, p.lon))) {
            all.add(p);
          }
        }
      } catch (_) {
        // A missing WPP file must not take the whole map down.
        continue;
      }
    }
    all.sort((DpiPoint a, DpiPoint b) => a.wpp.compareTo(b.wpp) != 0
        ? a.wpp.compareTo(b.wpp)
        : a.nomor.compareTo(b.nomor));
    _dpiCache = all;
    return all;
  }

  /// Weather is live-only, deliberately.
  ///
  /// There used to be a bundled `weather.json` sample with two invented areas
  /// and 48 invented hours. A forecast is a statement about the next two days:
  /// shipped inside an APK it is wrong from the moment it is built, yet it
  /// still draws a full 48-hour table and a sea-status colour, which is worse
  /// than drawing nothing. Whatever BMKG published is cached separately by
  /// [AppState] and only re-used while its hours are still in the future, so
  /// this method returns only that.
  Future<List<WeatherArea>> loadWeather({bool forceReload = false}) async {
    if (_weatherCache != null && !forceReload) return _weatherCache!;
    _weatherCache = const <WeatherArea>[];
    return _weatherCache!;
  }

  /// Nearest N DPI points from a position, optionally limited to a radius.
  static List<DpiPoint> nearby(
    List<DpiPoint> points,
    double lat,
    double lon, {
    int limit = 5,
    double? radiusKm,
  }) {
    final List<DpiPoint> filtered = radiusKm == null
        ? points
        : points.where((DpiPoint p) => p.distanceKmTo(lat, lon) <= radiusKm).toList();
    filtered.sort((DpiPoint a, DpiPoint b) =>
        a.distanceKmTo(lat, lon).compareTo(b.distanceKmTo(lat, lon)));
    return filtered.take(limit).toList();
  }

  /// Rows the worker flagged as low-confidence OCR would carry `ocr_conf < 20`;
  /// exposed here so the UI can show the "perlu review" chip.
  static bool needsReview(DpiPoint p) => p.ocrConf < 20;
}

